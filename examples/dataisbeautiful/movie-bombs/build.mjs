import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const data = JSON.parse(fs.readFileSync(path.join(here, 'data.json')));
const fonts = [['Anton', 400, 'anton-400.ttf'], ['IBM Plex Sans', 400, 'ibm-plex-sans-400.ttf'], ['IBM Plex Sans', 600, 'ibm-plex-sans-600.ttf']].map(([name, weight, file]) => `@font-face {font-family:'${name}';font-weight:${weight};font-style:normal;font-display:swap;src:url(data:font/ttf;base64,${fs.readFileSync(path.join(here, 'assets', file)).toString('base64')}) format('truetype');}`).join('\n');
for (const row of data.rows) row.art = 'data:image/jpeg;base64,' + fs.readFileSync(path.join(here, 'assets', row.id + '.jpg')).toString('base64');
const download = fs.readFileSync(path.join(root, 'skills/rhp/references/download.md'), 'utf8').match(/```html\n([\s\S]*?)\n```/)[1];
const page = fs.readFileSync(path.join(here, 'poster.template.html'), 'utf8').replace('__FONTS__', fonts).replace('__DATA__', JSON.stringify(data)).replace('__DOWNLOAD__', download);
fs.writeFileSync(path.join(here, 'movie-bombs.html'), page);
console.log(`Built movie-bombs.html with ${data.rows.length} embedded posters.`);
